#!/usr/bin/env python3
"""Writes targets/glide_dll/glide.def (Glide 2.1.1, glide.dll) from
targets/glide_dll/glide2x.def.

glide.dll is the glide2x.dll core plus core/glide211_abi.c: every Glide 2.x
export under the same name, and the Glide 2.1.1 functions below (stdcall
argument bytes as in 3dfx's glide.dll, checked against the imports of
Scorched Planet, Pandemonium! and CyberGladiators)."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

GLIDE211 = [
    ("grSstOpen", 24),
    ("grSstPassthruMode", 4),
    ("grLfbBegin", 0),
    ("grLfbEnd", 0),
    ("grLfbGetWritePtr", 4),
    ("grLfbGetReadPtr", 4),
    ("grLfbWriteMode", 4),
    ("grLfbBypassMode", 4),
    ("grLfbOrigin", 4),
]


def main():
    src = os.path.join(ROOT, "targets", "glide_dll", "glide2x.def")
    exports = [l.rstrip("\n") for l in open(src) if l.startswith("    ")]
    names = {l.split("=")[0].strip() for l in exports}
    for name, n in GLIDE211:
        sym = "_%s@%d" % (name, n)
        if sym in names:
            raise SystemExit("%s is already in glide2x.def" % sym)
        exports.append("    %s = %s@%d" % (sym, name, n))
    exports.sort(key=lambda l: l.split("=")[0].strip().lower())
    lines = ["; GENERATED by tools/abi/gen_glide211.py from glide2x.def -- do not edit by hand.",
             "LIBRARY glide.dll", "EXPORTS"] + exports
    with open(os.path.join(ROOT, "targets", "glide_dll", "glide.def"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
