#!/usr/bin/env python3
"""Writes targets/glide_dll/glide3x.def from abi/glide3x.api.

glide3x.dll exports the names of 3dfx's glide3x.dll, __stdcall-decorated
(_grDrawTriangle@12). The implementations are g3_<name> in core/glide3_abi.c
(the Glide 2 functions of the shared core keep their own names, renamed to
g2_* in this build, see GLIDULATOR_GLIDE3 in glide2x.h)."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def load(path):
    funcs = []
    for line in open(path):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, ret, args = [p.strip() for p in line.split("|")]
        n = 0 if args in ("", "void") else 4 * (args.count(",") + 1)
        funcs.append((name, n))
    return funcs


def main():
    funcs = load(os.path.join(ROOT, "abi", "glide3x.api"))
    lines = ["; GENERATED by tools/abi/gen_glide3x.py from abi/glide3x.api -- do not edit by hand.",
             "LIBRARY glide3x.dll", "EXPORTS"]
    for name, n in funcs:
        lines.append("    _%s@%d = g3_%s@%d" % (name, n, name, n))
    with open(os.path.join(ROOT, "targets", "glide_dll", "glide3x.def"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print("gen_glide3x: %d exports" % len(funcs))


if __name__ == "__main__":
    main()
